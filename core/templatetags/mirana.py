from django import template
from django.utils.http import urlencode

from core.jalali import jalali, to_fa_digits

register = template.Library()


@register.filter
def fa(value):
    if value is None:
        return ""
    return to_fa_digits(value)


@register.filter
def price(value):
    try:
        value = int(value)
    except (TypeError, ValueError):
        return value
    return to_fa_digits(f"{value:,}".replace(",", "٬"))


@register.filter
def jdate(value, fmt="date"):
    return jalali(value, fmt)


@register.filter
def multiply(a, b):
    try:
        return int(a) * int(b)
    except (TypeError, ValueError):
        return 0


@register.filter
def get_item(d, key):
    try:
        return d.get(key)
    except AttributeError:
        return None


@register.simple_tag(takes_context=True)
def query_replace(context, **kwargs):
    params = context["request"].GET.copy()
    for k, v in kwargs.items():
        if v in (None, ""):
            params.pop(k, None)
        else:
            params[k] = v
    return "?" + urlencode(params, doseq=True) if params else "?"


